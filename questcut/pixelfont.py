GLYPHS = {k: np.array([[c == "1" for c in row] for row in v.split()], dtype=bool) for k, v in _G.items()}
GW, GH = 5, 7          # glyph size
ADV = 6                # advance (1 px gap)


def _norm(ch: str) -> str:
    if ch in GLYPHS:
        return ch
    u = ch.upper()
    if u in GLYPHS:
        return u
    d = unicodedata.normalize("NFKD", ch)
    base = "".join(c for c in d if not unicodedata.combining(c)).upper()
    if base and base[0] in GLYPHS:
        return base[0]
    return "?"


def text_mask(text: str) -> np.ndarray:
    """Boolean mask (7, 6*len) for one line of text."""
    n = max(1, len(text))
    m = np.zeros((GH, n * ADV), dtype=bool)
    for i, ch in enumerate(text):
        m[:, i * ADV:i * ADV + GW] = GLYPHS[_norm(ch)]
    return m[:, :max(1, n * ADV - 1)]


def text_width(text: str) -> int:
    return max(1, len(text) * ADV - 1)
