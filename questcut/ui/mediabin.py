ROLE = Qt.ItemDataRole.UserRole


def _mime(payload):
    md = QMimeData()
    md.setData(MIME, json.dumps(payload).encode())
    return md


class DragList(QListWidget):
    def __init__(self, on_activate):
        super().__init__()
        self.setDragEnabled(True)
        self.setSelectionMode(QAbstractItemView.SelectionMode.ExtendedSelection)
        self.itemDoubleClicked.connect(lambda it: on_activate(it.data(ROLE)))

    def startDrag(self, actions):
        it = self.currentItem()
        if it is None or not it.data(ROLE):
            return
        d = QDrag(self)
        d.setMimeData(_mime(it.data(ROLE)))
        if not it.icon().isNull():
            d.setPixmap(it.icon().pixmap(64, 36))
        d.exec(Qt.DropAction.CopyAction)


class DragTree(QTreeWidget):
    def __init__(self, on_activate):
        super().__init__()
        self.setHeaderHidden(True)
        self.setDragEnabled(True)
        self.itemDoubleClicked.connect(lambda it, col: it.data(0, ROLE) and on_activate(it.data(0, ROLE)))

    def startDrag(self, actions):
        it = self.currentItem()
        if it is None or not it.data(0, ROLE):
            return
        d = QDrag(self)
        d.setMimeData(_mime(it.data(0, ROLE)))
        d.exec(Qt.DropAction.CopyAction)


