    def default_style(self):
        return self.style_combo.currentData()

    def _add_current(self, tree):
        it = tree.currentItem()
        if it is not None and it.data(0, ROLE):
            self.mw.add_item(it.data(0, ROLE), self.mw.playhead, None)

    def _listen(self):
        it = self.sound_tree.currentItem()
        if it is None or not it.data(0, ROLE):
            return
        path = self.mw.game_sound_path(it.data(0, ROLE)["name"])
        from ..backend import AUDIO
        if AUDIO["checked"] and AUDIO["outputs"] == 0:
            self.mw.status("No sound output found on this computer.")
            return
        try:
            from PySide6.QtMultimedia import QAudioOutput, QMediaPlayer
            if self._player is None:
                self._player = QMediaPlayer()
                self._out = QAudioOutput()
                self._player.setAudioOutput(self._out)
            self._player.stop()
            self._player.setSource(QUrl.fromLocalFile(path))
            self._player.play()
        except Exception as e:
            self.mw.status(f"Can't play sound here: {e}")

    def _remove_media(self):
        for it in self.media_list.selectedItems():
            self.mw.remove_media(it.data(ROLE)["id"])

    def refresh_media(self):
        sel = {it.data(ROLE)["id"] for it in self.media_list.selectedItems()}
        self.media_list.clear()
        for m in self.mw.project.media.values():
            if m.generated:
                continue
            text = m.name
            if m.kind in ("video", "audio"):
                text += f"\n{fmt_time(m.duration)}  ·  {m.kind}"
                if m.kind == "video":
                    text += f"  {m.width}×{m.height}"
            else:
                text += "\npicture"
            if m.id in self.mw.proxy_jobs:
                text += "  · preparing preview…"
            it = QListWidgetItem(text)
            it.setData(ROLE, {"type": "media", "id": m.id})
            th = self.mw.thumbs.get(m.id)
            if th is not None:
                it.setIcon(QIcon(th))
            self.media_list.addItem(it)
            if m.id in sel:
                it.setSelected(True)
